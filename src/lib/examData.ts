// Helper to get exam by slug
export function getExam(slug: string): ExamInfo | undefined {
  return EXAMS.find((e) => e.slug === slug);
}

// Helper to get all topics for an exam (flattened)
export function getAllTopics(exam: ExamInfo): { moduleId: number; topicId: string; name: string }[] {
  const topics: { moduleId: number; topicId: string; name: string }[] = [];
  exam.syllabus.forEach((mod, mi) => {
    mod.topics.forEach((t) => {
      topics.push({ moduleId: mi, topicId: t.id, name: t.name });
    });
  });
  return topics;
}

// Helper to count total topics
export function getTopicCount(exam: ExamInfo): number {
  return exam.syllabus.reduce((sum, mod) => sum + mod.topics.length, 0);
}
